import React, { useEffect, useMemo, useRef, useState } from "react";
import {
  View,
  Text,
  StyleSheet,
  TouchableOpacity,
  StatusBar,
  ScrollView,
  useWindowDimensions,
  ActivityIndicator,
  Alert,
  Platform,
} from "react-native";

import { MaterialIcons, Ionicons } from "@expo/vector-icons";
import QRCode from "react-native-qrcode-svg";
import * as ScreenOrientation from "expo-screen-orientation";
import * as MediaLibrary from "expo-media-library";
import { captureRef } from "react-native-view-shot";
import { useNavigation } from "@react-navigation/native";

import { useAuth } from "../../context/AuthContext";

const licenceCategories = [
  { code: "A", vehicle: "Motorcycle" },
  { code: "A1", vehicle: "Motorcycle" },
  { code: "B", vehicle: "Light Motor Vehicle" },
  { code: "C1", vehicle: "Medium Motor Vehicle" },
  { code: "C", vehicle: "Heavy Motor Vehicle" },
  { code: "EB", vehicle: "Light Vehicle + Trailer" },
  { code: "EC1", vehicle: "Medium Motor Vehicle + Trailer" },
  { code: "EC", vehicle: "Heavy Motor Vehicle + Trailer" },
];

export default function DigitalLicenseScreen() {
  const { user } = useAuth();
  const navigation = useNavigation();
  const { width, height } = useWindowDimensions();

  const licenseCardRef = useRef<View>(null);
  const [isSaving, setIsSaving] = useState(false);

  const isCompact = height < 450 || width < 700;

  useEffect(() => {
    const lockLandscape = async () => {
      try {
        await ScreenOrientation.lockAsync(
          ScreenOrientation.OrientationLock.LANDSCAPE
        );
      } catch (error) {
        console.log("Could not lock landscape:", error);
      }
    };

    lockLandscape();

    return () => {
      ScreenOrientation.lockAsync(
        ScreenOrientation.OrientationLock.PORTRAIT
      ).catch((error) => {
        console.log("Could not restore portrait:", error);
      });
    };
  }, []);

  const fullName = user?.fullName ?? "";

  const initials = useMemo(() => {
    return (
      fullName
        .trim()
        .split(/\s+/)
        .filter(Boolean)
        .map((part) => part.charAt(0))
        .join("")
        .toUpperCase() || "--"
    );
  }, [fullName]);

  const licenseNumber = user?.driverLicense?.number ?? "N/A";
  const licenseCategory = user?.driverLicense?.class ?? "N/A";
  const issueDate = user?.driverLicense?.issueDate ?? "N/A";
  const expiryDate = user?.driverLicense?.expiryDate ?? "N/A";
  const status = user?.driverLicense?.status ?? "Unknown";

  const documentNumber = user?.idNumber ?? "N/A";
  const gender = user?.gender ?? "N/A";
  const birthDate = user?.birthDate ?? "N/A";

  const cardNumber = user?.driverLicense?.cardNumber ?? "N/A";
  const qrToken = user?.digitalLicense?.qrToken ?? "";

  const normalisedCategory = licenseCategory
    .replace(/^Code\s+/i, "")
    .trim()
    .toUpperCase();

  const hasMatchingCategory = licenceCategories.some(
    (category) => category.code === normalisedCategory
  );

  /*
   * Prefer the QR token generated by your backend.
   * The fallback preserves QR functionality for existing records
   * where digitalLicense.qrToken has not yet been populated.
   */
  const qrValue = qrToken
    ? qrToken
    : JSON.stringify({
        licenseNumber,
        licenseCategory,
        expiryDate,
        status,
      });

  const isValid = status.trim().toLowerCase() === "valid";

  const saveLicense = async () => {
    if (!licenseCardRef.current) {
      Alert.alert("Unable to save", "The licence card is not ready yet.");
      return;
    }

    try {
      setIsSaving(true);

      const permission = await MediaLibrary.requestPermissionsAsync();

      if (!permission.granted) {
        Alert.alert(
          "Permission required",
          "Allow gallery access so TrafficConnect SA can save your digital licence."
        );
        return;
      }

      const uri = await captureRef(licenseCardRef, {
        format: "png",
        quality: 1,
        result: "tmpfile",
      });

      await MediaLibrary.saveToLibraryAsync(uri);

      Alert.alert(
        "Licence saved",
        "Your digital driver's licence has been saved to your gallery."
      );
    } catch (error) {
      console.log("Licence download error:", error);

      Alert.alert(
        "Download failed",
        "We could not save your digital licence. Please try again."
      );
    } finally {
      setIsSaving(false);
    }
  };

  if (!user) {
    return (
      <View style={styles.loadingContainer}>
        <StatusBar hidden />

        <MaterialIcons name="credit-card" size={45} color="#FFFFFF" />

        <Text style={styles.loadingText}>
          Loading digital licence...
        </Text>
      </View>
    );
  }

  return (
    <View style={styles.screen}>
      <StatusBar hidden />

      {/* BACK BUTTON */}
      <TouchableOpacity
        style={styles.backButton}
        onPress={() => navigation.goBack()}
        activeOpacity={0.8}
      >
        <Ionicons name="arrow-back" size={20} color="#FFFFFF" />
        <Text style={styles.backText}>Back</Text>
      </TouchableOpacity>

      {/* DOWNLOAD BUTTON */}
      <TouchableOpacity
        style={[
          styles.downloadButton,
          isSaving && styles.downloadButtonDisabled,
        ]}
        onPress={saveLicense}
        disabled={isSaving}
        activeOpacity={0.85}
      >
        {isSaving ? (
          <ActivityIndicator size="small" color="#FFFFFF" />
        ) : (
          <MaterialIcons
            name="file-download"
            size={19}
            color="#FFFFFF"
          />
        )}

        <Text style={styles.downloadText}>
          {isSaving ? "Saving..." : "Download Licence"}
        </Text>
      </TouchableOpacity>

      <ScrollView
        style={styles.scrollView}
        contentContainerStyle={[
          styles.scrollContent,
          {
            paddingTop: isCompact ? 48 : 58,
            paddingBottom: isCompact ? 16 : 28,
          },
        ]}
        showsVerticalScrollIndicator={false}
      >
        {/* THE COMPLETE CARD IS CAPTURED FOR DOWNLOAD */}
        <View
          ref={licenseCardRef}
          collapsable={false}
          style={[
            styles.licenseCard,
            {
              maxWidth: isCompact ? 900 : 1100,
            },
          ]}
        >
          {/* HEADER */}
          <View
            style={[
              styles.header,
              isCompact && styles.headerCompact,
            ]}
          >
            <View style={styles.headerLeft}>
              <View style={styles.govIcon}>
                <MaterialIcons
                  name="account-balance"
                  size={isCompact ? 23 : 28}
                  color="#FFFFFF"
                />
              </View>

              <View style={styles.headerTextContainer}>
                <Text style={styles.department}>
                  DEPARTMENT OF TRANSPORT
                </Text>

                <Text style={styles.country}>
                  REPUBLIC OF SOUTH AFRICA
                </Text>
              </View>
            </View>

            <View style={styles.headerRight}>
              <Ionicons
                name="shield-checkmark"
                size={17}
                color="#FFFFFF"
              />

              <Text style={styles.digitalText}>
                DIGITAL DRIVER'S LICENCE
              </Text>
            </View>
          </View>

          {/* MAIN INFORMATION */}
          <View
            style={[
              styles.mainContent,
              isCompact && styles.mainContentCompact,
            ]}
          >
            {/* DRIVER PROFILE */}
            <View
              style={[
                styles.profileSection,
                isCompact && styles.profileSectionCompact,
              ]}
            >
              <View
                style={[
                  styles.initialsCircle,
                  isCompact && styles.initialsCircleCompact,
                ]}
              >
                <Text
                  style={[
                    styles.initialsLarge,
                    isCompact && styles.initialsLargeCompact,
                  ]}
                >
                  {initials}
                </Text>
              </View>

              <Text
                style={[
                  styles.fullName,
                  isCompact && styles.fullNameCompact,
                ]}
                numberOfLines={2}
              >
                {fullName || "Not Available"}
              </Text>

              <Text style={styles.initialsLabel}>
                Initials: {initials}
              </Text>

              <View
                style={[
                  styles.statusBadge,
                  isValid ? styles.valid : styles.invalid,
                ]}
              >
                <View
                  style={[
                    styles.statusDot,
                    isValid ? styles.validDot : styles.invalidDot,
                  ]}
                />

                <Text
                  style={[
                    styles.statusText,
                    isValid ? styles.validText : styles.invalidText,
                  ]}
                >
                  {status.toUpperCase()}
                </Text>
              </View>
            </View>

            {/* DRIVER DETAILS */}
            <View style={styles.detailsSection}>
              <Text style={styles.sectionTitle}>
                DRIVER INFORMATION
              </Text>

              <View style={styles.detailsGrid}>
                <Info label="Licence Number" value={licenseNumber} />
                <Info
                  label="Current Category"
                  value={licenseCategory}
                  highlight
                />
                <Info
                  label="ID / Document Number"
                  value={documentNumber}
                />
                <Info label="Gender" value={gender} />
                <Info label="Date of Birth" value={birthDate} />
                <Info label="Issue Date" value={issueDate} />
                <Info label="Expiry Date" value={expiryDate} />
                <Info label="Card Number" value={cardNumber} />
              </View>
            </View>

            {/* QR CODE */}
            <View style={styles.qrSection}>
              <View style={styles.qrContainer}>
                <QRCode
                  value={qrValue || "TRAFFICCONNECT-LICENCE"}
                  size={isCompact ? 76 : 94}
                  backgroundColor="#FFFFFF"
                  color="#003366"
                  quietZone={5}
                />
              </View>

              <Text style={styles.qrTitle}>SCAN TO VERIFY</Text>

              <Text style={styles.qrSubtitle}>
                Digital licence QR
              </Text>
            </View>
          </View>

          {/* LICENCE CATEGORIES */}
          <View style={styles.categoriesSection}>
            <View style={styles.categoriesHeader}>
              <View style={styles.categoriesHeading}>
                <Text style={styles.categoriesTitle}>
                  LICENCE CATEGORIES
                </Text>

                <Text style={styles.categoriesSubtitle}>
                  Vehicle types associated with each licence category
                </Text>
              </View>

              <View style={styles.currentCategoryBadge}>
                <Text style={styles.currentCategoryLabel}>
                  YOUR CATEGORY
                </Text>

                <Text style={styles.currentCategoryValue}>
                  {licenseCategory}
                </Text>
              </View>
            </View>

            <View style={styles.categoryGrid}>
              {licenceCategories.map((category) => {
                const isCurrentCategory =
                  category.code === normalisedCategory;

                return (
                  <View
                    key={category.code}
                    style={[
                      styles.categoryCard,
                      isCurrentCategory &&
                        styles.categoryCardSelected,
                    ]}
                  >
                    <View
                      style={[
                        styles.categoryCode,
                        isCurrentCategory &&
                          styles.categoryCodeSelected,
                      ]}
                    >
                      <Text
                        style={[
                          styles.categoryCodeText,
                          isCurrentCategory &&
                            styles.categoryCodeTextSelected,
                        ]}
                      >
                        {category.code}
                      </Text>
                    </View>

                    <View style={styles.categoryVehicleContainer}>
                      <Text
                        style={[
                          styles.categoryVehicle,
                          isCurrentCategory &&
                            styles.categoryVehicleSelected,
                        ]}
                      >
                        {category.vehicle}
                      </Text>

                      {isCurrentCategory && (
                        <View style={styles.selectedBadge}>
                          <Ionicons
                            name="checkmark-circle"
                            size={13}
                            color="#2E7D32"
                          />

                          <Text style={styles.selectedText}>
                            YOUR CATEGORY
                          </Text>
                        </View>
                      )}
                    </View>
                  </View>
                );
              })}
            </View>

            {!hasMatchingCategory && (
              <Text style={styles.categoryNotice}>
                Your recorded category ({licenseCategory}) does not match
                one of the categories displayed above.
              </Text>
            )}
          </View>

          {/* FOOTER */}
          <View style={styles.footer}>
            <View style={styles.footerLeft}>
              <MaterialIcons
                name="verified-user"
                size={16}
                color="#003366"
              />

              <Text style={styles.footerText}>
                Government-issued digital credential
              </Text>
            </View>

            <Text style={styles.footerLicense}>
              Licence No. {licenseNumber}
            </Text>

            <Text style={styles.footerCountry}>
              SOUTH AFRICA
            </Text>
          </View>
        </View>
      </ScrollView>
    </View>
  );
}

/* =========================================================
   INFORMATION COMPONENT
========================================================= */

function Info({
  label,
  value,
  highlight = false,
}: {
  label: string;
  value: string;
  highlight?: boolean;
}) {
  return (
    <View
      style={[
        styles.infoItem,
        highlight && styles.infoItemHighlight,
      ]}
    >
      <Text style={styles.infoLabel}>{label}</Text>

      <Text
        style={[
          styles.infoValue,
          highlight && styles.infoValueHighlight,
        ]}
        numberOfLines={1}
      >
        {value}
      </Text>
    </View>
  );
}

